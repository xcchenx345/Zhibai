package com.zhibai.app.data

import android.content.Context
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.io.File
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Encrypted chat history backup.
 *
 * Saves to external files dir (survives app update, cleared on uninstall).
 * Uses Android Keystore AES-GCM for encryption — key never leaves secure hardware.
 *
 * Flow:
 * 1. On each saveSessions(), also write encrypted backup
 * 2. On startup, if sessions are empty but backup exists → restore, then delete backup
 */
object ChatBackupManager {

    private const val BACKUP_DIR = "zhibai_backup"
    private const val BACKUP_FILE = "sessions.enc"
    private const val KEY_ALIAS = "zhibai_chat_backup_key"
    private const val GCM_TAG_BITS = 128
    private const val GCM_IV_BYTES = 12

    /** Write encrypted backup of the sessions file to external storage.
     *  Streams file -> CipherOutputStream so neither plaintext nor ciphertext is
     *  materialized as one big array (that OOMed on long histories). */
    fun backupFile(context: Context, src: File) {
        try {
            val dir = File(context.getExternalFilesDir(null), BACKUP_DIR)
            if (!dir.exists()) dir.mkdirs()
            val file = File(dir, BACKUP_FILE)

            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
            val iv = cipher.iv  // 12 bytes generated by GCM

            // Format: [1 byte IV length][IV][ciphertext+tag] - unchanged on disk.
            java.io.FileOutputStream(file).use { out ->
                out.write(byteArrayOf(iv.size.toByte()) + iv)
                javax.crypto.CipherOutputStream(out, cipher).use { cos ->
                    src.inputStream().use { it.copyTo(cos) }
                }
            }
        } catch (_: Exception) { }
    }

    /**
     * Try to restore from backup.
     * Returns the decrypted sessions JSON, or null if no backup / decrypt fails.
     * Deletes the backup file after successful read.
     */
    fun restore(context: Context): String? {
        return try {
            val file = File(File(context.getExternalFilesDir(null), BACKUP_DIR), BACKUP_FILE)
            if (!file.exists()) return null

            val bytes = file.readBytes()
            if (bytes.size < 5) { file.delete(); return null }

            val ivLen = bytes[0].toInt()
            val iv = bytes.copyOfRange(1, 1 + ivLen)
            val ciphertext = bytes.copyOfRange(1 + ivLen, bytes.size)

            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
            val plain = cipher.doFinal(ciphertext)
            val json = String(plain, Charsets.UTF_8)

            // Delete backup after successful restore
            file.delete()
            json
        } catch (_: Exception) {
            // Corrupted or key lost — delete to avoid repeated failures
            try {
                File(File(context.getExternalFilesDir(null), BACKUP_DIR), BACKUP_FILE).delete()
            } catch (_: Exception) { }
            null
        }
    }

    /** Check if a backup file exists. */
    fun hasBackup(context: Context): Boolean {
        return File(File(context.getExternalFilesDir(null), BACKUP_DIR), BACKUP_FILE).exists()
    }

    // ── Keystore key management ──────────────────────────────────────

    private fun getOrCreateKey(): SecretKey {
        val keyStore = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }

        // Return existing key if present
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let {
            return it.secretKey
        }

        // Generate new key
        val generator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore"
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }
}
